// Copies drizzle-kit's SQL migrations into a TypeScript module, so the app carries them
// inside its bundle (no migrations folder to locate at runtime). Run via `npm run db:generate`.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'drizzle'
const journal = JSON.parse(readFileSync(join(dir, 'meta', '_journal.json'), 'utf8'))
const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({ tag: e.tag, sql: readFileSync(join(dir, `${e.tag}.sql`), 'utf8') }))

const out = `// GENERATED by scripts/embed-migrations.mjs from drizzle/. Do not edit by hand.
export const MIGRATIONS: ReadonlyArray<{ tag: string; sql: string }> = ${JSON.stringify(migrations, null, 2)}
`
writeFileSync('src/main/store/migrations.generated.ts', out)
console.log(`${migrations.length} migrasyon gömüldü: ${migrations.map((m) => m.tag).join(', ')}`)
